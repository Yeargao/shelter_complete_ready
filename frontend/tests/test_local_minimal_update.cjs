const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const root=path.resolve(__dirname,'../src');
const file=f=>fs.readFileSync(path.join(root,f),'utf8');
const code=file('components/common/timelineLayout.ts');
const compiled=ts.transpileModule(code,{fileName:'timelineLayout.ts',reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
assert.equal(compiled.diagnostics.length,0,'columns calculation parses');
const testModule={exports:{}};
new Function('module','exports',compiled.outputText)(testModule,testModule.exports);
const columns=testModule.exports.timelineColumns;
const T=(id,s,e)=>({task_id:id,s,e});
const single=columns([T('A',540,555),T('B',555,570),T('C',570,600),T('D',600,660)]);
for(const c of single.values())assert.equal(c.count,1,'adjacent 15m tasks stay stacked, never adjacent columns');
const two=columns([T('A',540,570),T('B',540,570)]);
assert.deepEqual(two.get('A'),{index:0,count:2});assert.deepEqual(two.get('B'),{index:1,count:2});
const three=columns([T('A',540,570),T('B',540,555),T('C',540,560)]);
for(const c of three.values())assert.equal(c.count,3);
const chain=columns([T('A',540,600),T('B',540,570),T('C',570,600)]);
assert.equal(chain.get('C').count,2,'lane reuse must not become an unnecessary third column');
